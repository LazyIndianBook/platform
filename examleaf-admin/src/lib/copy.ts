export type Copy = typeof en;

/** The console's words. One language for now; the person's language picks the object once the others exist. */
export const copy: Copy = en;

/** A code the API sends that no table here names ("sync_failure"): its words, as a fallback ("Sync failure"). */
export function humanize(code: string): string {
  const words = code.replace(/[_-]+/g, " ").trim();
  return words ? words[0].toUpperCase() + words.slice(1).toLowerCase() : code;
}

/** The label of a known code, else its humanized words. */
export function labelOf(table: Record<string, string>, code: string | null | undefined): string {
  if (!code) return copy.common.unknown;
  return table[code] ?? humanize(code);
}
